package main

import (
	"encoding/json"
	"fmt"
	"slices"
	"sort"
	"strings"

	"github.com/Sebas1705/WinForge/internal/eol"
)

// apiCycle is one entry of https://endoflife.date/api/<product>.json. Several fields are a date
// or a boolean depending on the product, so they are decoded loosely.
type apiCycle struct {
	Cycle       string          `json:"cycle"`
	ReleaseDate string          `json:"releaseDate"`
	EOL         json.RawMessage `json:"eol"`
	LTS         json.RawMessage `json:"lts"`
}

// dateOrBool reads a value that is "YYYY-MM-DD", true or false. date is "" for the booleans.
func dateOrBool(raw json.RawMessage) (date string, flag bool, err error) {
	s := strings.TrimSpace(string(raw))
	switch s {
	case "", "null", "false":
		return "", false, nil
	case "true":
		return "", true, nil
	}
	var d string
	if err := json.Unmarshal(raw, &d); err != nil {
		return "", false, fmt.Errorf("unexpected value %s", s)
	}
	if _, err := eol.ParseDay(d); err != nil {
		return "", false, fmt.Errorf("%q is not a date", d)
	}
	return d, true, nil
}

// buildProduct turns one product's API answer into a data product. A cycle is kept when it is
// released, is supported (no end announced) or ended on or after keepEndedSince, and, if the spec
// lists cycles, is one of them. A cycle whose end is "true" (ended, no date) cannot be stated and
// is skipped, with a note in the returned warnings.
func buildProduct(s spec, body []byte, asOf string) (eol.Product, []string, error) {
	var raw []apiCycle
	if err := json.Unmarshal(body, &raw); err != nil {
		return eol.Product{}, nil, fmt.Errorf("%s: %w", s.Slug, err)
	}
	p := eol.Product{
		ID: s.ID, Name: s.Name, Source: "https://endoflife.date/" + s.Slug, Scheme: s.Scheme,
		Apps: slices.Clone(s.Apps), Follows: s.Follows,
	}
	var warns []string
	have := map[string]bool{}
	for _, c := range raw {
		have[c.Cycle] = true
		if len(s.Only) > 0 && !slices.Contains(s.Only, c.Cycle) {
			continue
		}
		if c.ReleaseDate != "" && c.ReleaseDate > asOf {
			continue // not released yet: nothing can be installed from it
		}
		end, ended, err := dateOrBool(c.EOL)
		if err != nil {
			return p, warns, fmt.Errorf("%s %s: eol: %w", s.Slug, c.Cycle, err)
		}
		if end == "" && ended {
			if c.ReleaseDate == "" || c.ReleaseDate >= keepEndedSince {
				warns = append(warns, fmt.Sprintf("%s %s: ended but no date given, skipped", s.Slug, c.Cycle))
			}
			continue
		}
		if end != "" && end < keepEndedSince && len(s.Only) == 0 {
			continue
		}
		lts := false
		if d, flag, err := dateOrBool(c.LTS); err != nil {
			return p, warns, fmt.Errorf("%s %s: lts: %w", s.Slug, c.Cycle, err)
		} else if d == "" {
			lts = flag
		} else {
			lts = d <= asOf // a date is the day the line becomes long-term
		}
		if lts && end == "" {
			// A long-term line with no end date is a gap in the source, not "supported forever".
			warns = append(warns, fmt.Sprintf("%s %s: long-term support with no end date, left out", s.Slug, c.Cycle))
			continue
		}
		p.Cycles = append(p.Cycles, eol.Cycle{Cycle: c.Cycle, EOL: end, LTS: lts, App: s.Install[c.Cycle]})
	}
	for _, c := range s.Only {
		if !have[c] {
			return p, warns, fmt.Errorf("%s: cycle %s is not in the source any more", s.Slug, c)
		}
	}
	for c := range s.Install {
		if !slices.ContainsFunc(p.Cycles, func(x eol.Cycle) bool { return x.Cycle == c }) {
			warns = append(warns, fmt.Sprintf("%s: install mapping for cycle %s has no cycle in the data", s.Slug, c))
		}
	}
	sort.SliceStable(p.Cycles, func(i, j int) bool { return eol.CompareCycles(p.Cycles[i].Cycle, p.Cycles[j].Cycle) > 0 })
	return p, warns, nil
}

const header = `# End-of-support dates for the software WinForge can find installed.
#
# GENERATED by cmd/winforge-eol and reviewed by a person; do not edit by hand. To change what is
# covered, edit cmd/winforge-eol/products.go and run:
#
#   go run ./cmd/winforge-eol
#
# The app only READS this file (it is embedded). It never fetches it and never sends the list of
# installed software or its versions anywhere. Dates are the last day of standard support for a
# release line, from the page named in each product's comment (endoflife.date, which follows the
# vendor's own page, also listed). A line whose date is not stated by the source is left out, so a
# version in it shows as "unknown" instead of with a guessed date. asOf is the day this table was
# checked; the app warns when it is more than a year old.
`

// render writes the data as YAML, the same way every time: products in the order of the spec
// list, cycles newest first, strings quoted.
func render(d *eol.Data, vendors map[string]string) []byte {
	var b strings.Builder
	b.WriteString(header)
	fmt.Fprintf(&b, "asOf: %q\nproducts:\n", d.AsOf)
	for _, p := range d.Products {
		if v := vendors[p.ID]; v != "" {
			fmt.Fprintf(&b, "  # %s: %s (vendor: %s)\n", p.Name, p.Source, v)
		} else {
			fmt.Fprintf(&b, "  # %s: %s\n", p.Name, p.Source)
		}
		fmt.Fprintf(&b, "  - id: %s\n    name: %q\n    source: %q\n", p.ID, p.Name, p.Source)
		if p.Scheme != "" {
			fmt.Fprintf(&b, "    scheme: %s\n", p.Scheme)
		}
		fmt.Fprintf(&b, "    apps: [%s]\n", strings.Join(p.Apps, ", "))
		if len(p.Follows) > 0 {
			ids := make([]string, 0, len(p.Follows))
			for id := range p.Follows {
				ids = append(ids, id)
			}
			sort.Strings(ids)
			parts := make([]string, len(ids))
			for i, id := range ids {
				parts[i] = id + ": " + p.Follows[id]
			}
			fmt.Fprintf(&b, "    follows: {%s}\n", strings.Join(parts, ", "))
		}
		b.WriteString("    cycles:\n")
		for _, c := range p.Cycles {
			fields := []string{fmt.Sprintf("cycle: %q", c.Cycle)}
			if c.EOL != "" {
				fields = append(fields, fmt.Sprintf("eol: %q", c.EOL))
			}
			if c.LTS {
				fields = append(fields, "lts: true")
			}
			if c.App != "" {
				fields = append(fields, "app: "+c.App)
			}
			fmt.Fprintf(&b, "      - {%s}\n", strings.Join(fields, ", "))
		}
	}
	return []byte(b.String())
}

// generate builds the whole file from a source of API answers (the network, or a folder).
func generate(specs []spec, fetch func(slug string) ([]byte, error), asOf string) (*eol.Data, []string, error) {
	d := &eol.Data{AsOf: asOf}
	var warns []string
	for _, s := range specs {
		body, err := fetch(s.Slug)
		if err != nil {
			return nil, warns, fmt.Errorf("%s: %w", s.Slug, err)
		}
		p, w, err := buildProduct(s, body, asOf)
		warns = append(warns, w...)
		if err != nil {
			return nil, warns, err
		}
		d.Products = append(d.Products, p)
	}
	return d, warns, nil
}

func vendorsOf(specs []spec) map[string]string {
	m := map[string]string{}
	for _, s := range specs {
		m[s.ID] = s.Vendor
	}
	return m
}

// diffLines lists the lines only in a (prefixed "-") and only in b (prefixed "+"), in file order,
// for the maintainer's cross-check. Identical files give nothing.
func diffLines(a, b string) []string {
	as, bs := strings.Split(a, "\n"), strings.Split(b, "\n")
	inA, inB := map[string]bool{}, map[string]bool{}
	for _, l := range as {
		inA[l] = true
	}
	for _, l := range bs {
		inB[l] = true
	}
	var out []string
	for _, l := range as {
		if !inB[l] {
			out = append(out, "- "+l)
		}
	}
	for _, l := range bs {
		if !inA[l] {
			out = append(out, "+ "+l)
		}
	}
	return out
}
